// Builds the lean <simscope-player> bundle (element + core) as one IIFE.
// Owned by the player-core work; see ../build.mjs for shared settings.
//
// The decode worker ships inside the bundle as a string: the worker entry is
// bundled on its own first and written to src/core/decode_worker.generated.js
// (committed, because the app bundle imports the same core and must not
// depend on build order), which the core turns into a Blob URL at run time.
import { build } from "esbuild";
import fs from "node:fs";
import path from "node:path";

async function buildWorkerSource({ here, common }) {
  const result = await build({
    ...common,
    entryPoints: [path.join(here, "src/core/decode_worker.js")],
    format: "iife",
    write: false,
    outdir: path.join(here, ".worker-out"),
  });
  const code = result.outputFiles[0].text;
  const file = path.join(here, "src/core/decode_worker.generated.js");
  const text = [
    "// Generated by build/player.mjs from decode_worker.js and format.js. Do not edit.",
    `export default ${JSON.stringify(code)};`,
    "",
  ].join("\n");
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) fs.writeFileSync(file, text);
}

export async function buildPlayer({ here, assets, common }) {
  await buildWorkerSource({ here, common });
  await build({
    ...common,
    entryPoints: [path.join(here, "src/element/index.js")],
    outfile: path.join(assets, "simscope-player.js"),
    format: "iife",
    globalName: "SimscopePlayer",
  });
  return ["simscope-player.js"];
}
